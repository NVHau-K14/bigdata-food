import pandas as pd, numpy as np
r = pd.read_csv("data/raw/food_vietnam/ratings.csv")
f = pd.read_csv("data/raw/food_vietnam/foods.csv")
print("columns foods:", list(f.columns)); print("foods rows:", len(f), "food_id min/max:", f.food_id.min() if 'food_id' in f else None, f.food_id.max() if 'food_id' in f else None)
print("ratings rows:", len(r)); print("dtypes:", dict(r.dtypes))
print("NULL per col:", r.isna().sum().to_dict())
print("n users:", r.userId.nunique(), "min/max userId:", r.userId.min(), r.userId.max())
print("n foods rated:", r.foodId.nunique(), "min/max foodId:", r.foodId.min(), r.foodId.max())
dup = r.duplicated(["userId","foodId"], keep=False)
print("rows in duplicated (user,food) groups:", int(dup.sum()), " extra rows (rows - distinct pairs):", len(r)-len(r.drop_duplicates(["userId","foodId"])))
print("distinct pairs:", len(r.drop_duplicates(["userId","foodId"])))
print("\nRating distribution:")
vc = r.rating.value_counts().sort_index(); print(pd.DataFrame({"n":vc,"pct":(vc/len(r)*100).round(2)}))
print("distinct rating values:", sorted(r.rating.dropna().unique().tolist()))
print("not multiple of 0.5:", int(((r.rating*2) % 1 != 0).sum()))
print("mean/std rating:", r.rating.mean(), r.rating.std(ddof=0))
per_user = r.groupby("userId").size()
print("\nratings per user: min/median/mean/max", per_user.min(), per_user.median(), per_user.mean(), per_user.max())
dpu = r.drop_duplicates(["userId","foodId"]).groupby("userId").size()
print("distinct foods per user: min/median/mean/max", dpu.min(), dpu.median(), dpu.mean(), dpu.max())
per_food = r.groupby("foodId").size()
print("ratings per food: min/median/mean/max", per_food.min(), per_food.median(), per_food.mean(), per_food.max())
dpf = r.drop_duplicates(["userId","foodId"]).groupby("foodId").size()
print("distinct users per food: min/median/mean/max", dpf.min(), dpf.median(), dpf.mean(), dpf.max())
print("foodId=4000 rows:", int((r.foodId==4000).sum()), " foodId not in foods:", int((~r.foodId.isin(f.food_id)).sum()))
print("foods never rated:", int((~f.food_id.isin(r.foodId)).sum()))
# duplicated pair: do ratings differ?
d = r[dup].groupby(["userId","foodId"]).rating.nunique()
print("dup groups:", len(d), " with differing ratings:", int((d>1).sum()))
print("uniform-11 std theory:", np.sqrt((11**2-1)/12)*0.5)
